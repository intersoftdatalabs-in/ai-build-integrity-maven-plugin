package com.intsof.ai.build.integrity;

import java.io.IOException;
import java.nio.file.DirectoryStream;
import java.nio.file.FileSystem;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.PathMatcher;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.project.MavenProject;

/**
 * Removes artifact digest files generated by the {@code generate-artifact-digests} goal.
 *
 * <p>This mojo scans the project's build directory for digest files (sidecar or central) and
 * deletes them. It binds by default to the {@code clean} phase and runs on each module.
 *
 * <p><b>Note:</b> Unlike the AI instruction file {@link HashCleanMojo} which uses {@code
 * executionRootOnly}, this mojo runs on <b>each module</b> to ensure cleanup of all digest files
 * across the reactor.
 */
@Mojo(
    name = "clean-artifact-digests",
    defaultPhase = LifecyclePhase.CLEAN,
    requiresProject = true,
    threadSafe = true)
public class ArtifactDigestsCleanMojo extends AbstractMojo {

  /** Default constructor for {@link ArtifactDigestsCleanMojo}. */
  public ArtifactDigestsCleanMojo() {}

  /** Current Maven project instance. */
  @Parameter(defaultValue = "${project}", readonly = true, required = true)
  private MavenProject project;

  /** Target build directory where artifacts and digests are located. */
  @Parameter(defaultValue = "${project.build.directory}", readonly = true, required = true)
  private String buildDirectory;

  /**
   * If true, skips the execution of the mojo. Accepts both {@code -Dai.integrity.skip=true} and the
   * Maven-conventional {@code -Dskip.ai.integrity=true}.
   */
  @Parameter(property = "ai.integrity.skip", defaultValue = "false")
  private boolean skip;

  /** Alternate Maven-conventional skip flag (e.g. -Dskip.ai.integrity=true). */
  @Parameter(property = "skip.ai.integrity", defaultValue = "false")
  private boolean skipAlt;

  /** Strategy for storing generated digests (SIDECAR or CENTRAL). */
  @Parameter(property = "ai.integrity.hashFileMode", defaultValue = "SIDECAR")
  private HashFileMode hashFileMode;

  /**
   * Array of algorithms used during generation. Used to determine which sidecar extensions to
   * clean.
   */
  @Parameter(property = "ai.integrity.algorithms", defaultValue = "SHA-256")
  private String[] algorithms;

  /** Explicit path to the central digest ledger file. */
  @Parameter(property = "ai.integrity.centralDigestFile")
  private String centralDigestFile;

  /** If true, also remove aggregate digest files. */
  @Parameter(property = "ai.integrity.cleanAggregateDigests", defaultValue = "true")
  private boolean cleanAggregateDigests;

  @Override
  public void execute() throws MojoExecutionException {
    if (skip || skipAlt) {
      getLog().info("Skipping execution.");
      return;
    }

    Path buildDir = Paths.get(buildDirectory);

    if (!Files.exists(buildDir)) {
      getLog().warn("Build directory does not exist: " + buildDir);
      return;
    }

    int deleted = 0;
    int failed = 0;

    if (hashFileMode == HashFileMode.CENTRAL) {
      DeleteResult result = deleteCentralDigestFile(buildDir);
      deleted += result.deleted;
      failed += result.failed;
    } else {
      DeleteResult result = deleteSidecarDigestFiles(buildDir);
      deleted += result.deleted;
      failed += result.failed;
    }

    // Clean aggregate digest files if enabled
    if (cleanAggregateDigests) {
      DeleteResult result = deleteAggregateDigestFiles(buildDir);
      deleted += result.deleted;
      failed += result.failed;
    }

    getLog()
        .info("Artifact digest cleanup complete: " + deleted + " deleted, " + failed + " failed.");

    if (failed > 0) {
      throw new MojoExecutionException("Failed to delete " + failed + " artifact digest files.");
    }
  }

  /**
   * Deletes the central digest ledger file.
   *
   * @param buildDir the build directory
   * @return delete result
   */
  private DeleteResult deleteCentralDigestFile(Path buildDir) {
    int deleted = 0;
    int failed = 0;

    Path centralFile = resolveCentralDigestFile(buildDir);
    if (Files.exists(centralFile)) {
      try {
        Files.delete(centralFile);
        getLog().debug("Deleted central digest file: " + centralFile);
        deleted++;
      } catch (IOException e) {
        getLog()
            .error("Failed to delete central digest file " + centralFile + ": " + e.getMessage());
        failed++;
      }
    }

    return new DeleteResult(deleted, failed);
  }

  /**
   * Deletes all sidecar digest files from the build directory.
   *
   * @param buildDir the build directory
   * @return delete result
   */
  private DeleteResult deleteSidecarDigestFiles(Path buildDir) {
    int deleted = 0;
    int failed = 0;

    FileSystem fs = buildDir.getFileSystem();
    Set<String> patterns = new HashSet<>();

    // Build patterns for all algorithm extensions
    for (String algorithm : algorithms) {
      patterns.add("**/*" + ArtifactDigestsUtils.extensionForAlgorithm(algorithm));
    }

    List<PathMatcher> matchers = new ArrayList<>();
    for (String pattern : patterns) {
      matchers.add(fs.getPathMatcher("glob:" + pattern));
      // Add fallback for root-level files
      if (pattern.startsWith("**/")) {
        matchers.add(fs.getPathMatcher("glob:" + pattern.substring(3)));
      }
    }

    List<Path> filesToDelete = new ArrayList<>();
    collectDigestFiles(buildDir, matchers, filesToDelete);

    if (filesToDelete.isEmpty()) {
      getLog().info("No sidecar digest files found to clean.");
      return new DeleteResult(0, 0);
    }

    getLog().info("Found " + filesToDelete.size() + " sidecar digest files to delete.");

    for (Path file : filesToDelete) {
      // Skip aggregate digest files - they are cleaned separately
      if (file.getFileName().toString().startsWith("ai-integrity-artifacts-aggregate")) {
        continue;
      }
      try {
        boolean wasDeleted = Files.deleteIfExists(file);
        if (wasDeleted) {
          getLog().debug("Deleted digest file: " + file);
          deleted++;
        }
      } catch (IOException e) {
        getLog().error("Failed to delete digest file " + file + ": " + e.getMessage());
        failed++;
      }
    }

    return new DeleteResult(deleted, failed);
  }

  /**
   * Deletes aggregate digest files from the build directory.
   *
   * @param buildDir the build directory
   * @return delete result
   */
  private DeleteResult deleteAggregateDigestFiles(Path buildDir) {
    int deleted = 0;
    int failed = 0;

    FileSystem fs = buildDir.getFileSystem();
    PathMatcher matcher = fs.getPathMatcher("glob:**/ai-integrity-artifacts-aggregate.sha256");

    List<Path> aggregateFiles = new ArrayList<>();
    try (DirectoryStream<Path> stream = Files.newDirectoryStream(buildDir, "*")) {
      for (Path entry : stream) {
        if (Files.isDirectory(entry)) {
          collectAggregateFiles(entry, matcher, aggregateFiles);
        } else if (matcher.matches(entry)) {
          aggregateFiles.add(entry);
        }
      }
    } catch (IOException e) {
      getLog().warn("Error scanning for aggregate digest files: " + e.getMessage());
    }

    for (Path file : aggregateFiles) {
      try {
        boolean wasDeleted = Files.deleteIfExists(file);
        if (wasDeleted) {
          getLog().debug("Deleted aggregate digest file: " + file);
          deleted++;
        }
      } catch (IOException e) {
        getLog().error("Failed to delete aggregate digest file " + file + ": " + e.getMessage());
        failed++;
      }
    }

    return new DeleteResult(deleted, failed);
  }

  /**
   * Recursively collects aggregate digest files.
   *
   * @param dir the directory to scan
   * @param matcher path matcher for aggregate files
   * @param results output list
   */
  private void collectAggregateFiles(Path dir, PathMatcher matcher, List<Path> results) {
    try (DirectoryStream<Path> stream = Files.newDirectoryStream(dir)) {
      for (Path entry : stream) {
        if (Files.isDirectory(entry)) {
          collectAggregateFiles(entry, matcher, results);
        } else if (matcher.matches(entry)) {
          results.add(entry);
        }
      }
    } catch (IOException e) {
      // Skip directories we can't read
    }
  }

  /**
   * Recursively collects sidecar digest files.
   *
   * @param dir the directory to scan
   * @param matchers path matchers for digest files
   * @param results output list
   */
  private void collectDigestFiles(Path dir, List<PathMatcher> matchers, List<Path> results) {
    try (DirectoryStream<Path> stream = Files.newDirectoryStream(dir)) {
      for (Path entry : stream) {
        if (Files.isDirectory(entry)) {
          collectDigestFiles(entry, matchers, results);
        } else {
          if (matchesAny(entry.getFileName(), matchers)) {
            results.add(entry);
          }
        }
      }
    } catch (IOException e) {
      // Skip directories we can't read
    }
  }

  /**
   * Resolves the central digest file path.
   *
   * @param buildDir the build directory
   * @return the resolved path
   */
  private Path resolveCentralDigestFile(Path buildDir) {
    if (centralDigestFile != null && !centralDigestFile.isEmpty()) {
      return Paths.get(centralDigestFile);
    }
    String ext = ArtifactDigestsUtils.extensionForAlgorithm(algorithms[0]);
    return buildDir.resolve("ai-integrity-artifacts" + ext);
  }

  /**
   * Tests if a path matches any of the provided matchers.
   *
   * @param path the path to check
   * @param matchers the compiled glob matchers
   * @return true if any matcher matches
   */
  private static boolean matchesAny(Path path, List<PathMatcher> matchers) {
    for (PathMatcher m : matchers) {
      if (m.matches(path)) {
        return true;
      }
    }
    return false;
  }

  /** Simple container for delete operation results. */
  private static class DeleteResult {
    final int deleted;
    final int failed;

    DeleteResult(int deleted, int failed) {
      this.deleted = deleted;
      this.failed = failed;
    }
  }
}
